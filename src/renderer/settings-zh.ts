export type CopyKey = keyof typeof copy;

export function localize(root: ParentNode = document): void {
  for (const element of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = element.dataset.i18n as CopyKey;
    if (key in copy) element.textContent = copy[key];
  }
  for (const element of root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]')) {
    const key = element.dataset.i18nPlaceholder as CopyKey;
    if (key in copy) element.placeholder = copy[key];
  }
}
