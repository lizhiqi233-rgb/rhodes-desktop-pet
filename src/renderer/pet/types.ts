import type { BaseTexture, TextureMatrix } from 'pixi.js';
import type { TextureAtlas } from '@pixi-spine/base';
import type { Spine } from '@pixi-spine/runtime-3.8';
import type { CarryMotion } from '../carry-motion.ts';
import type { HeadMotion } from '../head-motion.ts';
import type { MotionPlayer } from '../motion-player.ts';
import type { RestKind } from '../rest-cycle.ts';
import type { Bounds } from '../model-bounds.ts';
import type { PreparedVoices } from '../../shared/contracts.ts';

export type Manifest = {
  id: string;
  name: string;
  spineVersion: string;
  voices: { file: string; label: string }[];
  sources: string[];
};
export type Voice = PreparedVoices['voices'][number];
export type AlphaPage = { width: number; height: number; pixels: Uint8Array };
export type AtlasPageCache = { alpha: AlphaPage; source: HTMLImageElement | HTMLCanvasElement };
export type VertexBuffer = { world: Float32Array; screen: Float32Array };
export type ViewportSize = { width: number; height: number };
export type PetModel = {
  id: string;
  skinId: string;
  atlas: TextureAtlas;
  spine: Spine;
  appointmentVoices: Voice[];
  talkVoices: Voice[];
  interactionVoices: Voice[];
  voicesReady: boolean;
  appointmentPlayed: boolean;
  idleAnimations: string[];
  moveAnimation: string | null;
  interactionAnimations: string[];
  restAnimations: Record<RestKind, string | null>;
  restBounds: Partial<Record<RestKind, Bounds>>;
  propBounds: Partial<Record<RestKind, Bounds>>;
  animationDurations: Map<string, number>;
  bounds: Bounds;
  actorBounds: Bounds;
  groundY: number;
  restOffsetY: number;
  alphaByTexture: Map<BaseTexture, AlphaPage>;
  vertices: WeakMap<object, VertexBuffer>;
  uvMatrices: WeakMap<object, TextureMatrix>;
  motion: MotionPlayer;
  head: HeadMotion;
  carry: CarryMotion;
  layoutX: number;
  layoutY: number;
  holdX: number;
  holdY: number;
};
export type PetMode = 'idle' | 'look' | 'head' | 'move' | 'interact' | 'drag' | 'land' | 'rest';
export type AmbientAction = 'look' | 'pace' | 'tilt' | 'nod' | 'rest' | 'idle';
